"""E: fuzzer baseline (no LLM). Schemathesis property-based testing as a RESTestBench tool.

For each requirement, the generated test registers a fresh user (same auth inference as our
agent), then runs Schemathesis with a fixed seed on the API paths that retrieval finds for the
requirement. The oracle ignores the requirement: the test fails only if the service crashes
(5xx) or a response breaks the schema the spec documents. This shows what a classic fuzzer's
oracle catches on the same planted bugs.
"""
from __future__ import annotations

import json
import pprint
import re
import sys
import time
from pathlib import Path
from urllib.parse import urlparse

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from agent.compiler import RUNTIME_SOURCE, infer_auth  # noqa: E402
from agent.retrieval import Retriever  # noqa: E402
from agent.spec import load_operations  # noqa: E402

CHECKS = "not_a_server_error,response_schema_conformance"
MAX_EXAMPLES = 25
TOP_K = 5

TEMPLATE = '''"""
Generated by the PreTrained fuzzer baseline (Schemathesis, requirement-blind oracle).
Requirement: {requirement}
"""
{runtime}

import subprocess as _subprocess
import sys as _sys
from pathlib import Path as _Path

BASE_URL = {base_url!r}
FUZZ_URL = {fuzz_url!r}
AUTH = {auth}
SPEC = {spec!r}
PATH_REGEX = {path_regex!r}
CHECKS = {checks!r}
MAX_EXAMPLES = {max_examples}
SEED = {seed}


def test_requirement():
    r = _Run({{"actors": {{"A": {{"type": "new_user"}}}}, "steps": [], "checks": []}}, AUTH, BASE_URL)
    r.setup_actor("A", {{"type": "new_user"}})
    token = r.actors["A"].get("token")
    st = _Path(_sys.executable).parent / "st"
    cmd = [str(st), "run", SPEC, "--url", FUZZ_URL, "--include-path-regex", PATH_REGEX,
           "--checks", CHECKS, "--max-examples", str(MAX_EXAMPLES), "--seed", str(SEED),
           "--phases", "examples,fuzzing", "--no-color"]
    if token:
        cmd += ["-H", "Authorization: " + (AUTH["header_prefix"] + " " + token).strip()]
    out = _subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    assert out.returncode == 0, "schemathesis found failures:\\n" + (out.stdout + out.stderr)[-3000:]
'''


class FuzzerTool:
    """Harness tool interface (non-interactive)."""
    INTERACTIVE = False
    test_file_name = "test.py"

    def __init__(self, seed: int = 1, name: str = "e_fuzzer"):
        self.seed = seed
        self.model_id = name
        self.request_count = 0
        self.total_input_tokens = 0
        self.total_output_tokens = 0
        self._retrievers = {}

    def get_test_command(self, test_file_path: str) -> str:
        return f'"{sys.executable}" -m pytest "{test_file_path}" -v --tb=short'

    def generate_test(self, scenario_description, test_file_path, test_dir_path, spec_path,
                      reset_script_path, service_base_url="http://localhost:8000"):
        service = Path(spec_path).parent.name
        Path(test_dir_path).mkdir(parents=True, exist_ok=True)
        t0 = time.time()
        if service not in self._retrievers:
            self._retrievers[service] = Retriever(service)
        ops = load_operations(service)
        selected = self._retrievers[service].rank(scenario_description, "hybrid_rerank")[:TOP_K]
        paths = sorted({o.path for o in selected})
        path_regex = "^(" + "|".join(re.escape(p) for p in paths) + ")$"
        servers = json.loads(Path(spec_path).read_text()).get("servers") or [{"url": ""}]
        fuzz_url = service_base_url.rstrip("/") + urlparse(servers[0]["url"]).path.rstrip("/")
        Path(test_file_path).write_text(TEMPLATE.format(
            requirement=scenario_description.replace('"""', "'''"), runtime=RUNTIME_SOURCE,
            base_url=service_base_url, fuzz_url=fuzz_url, auth=pprint.pformat(infer_auth(service, ops), indent=1, width=100),
            spec=str(Path(spec_path).resolve()), path_regex=path_regex, checks=CHECKS,
            max_examples=MAX_EXAMPLES, seed=self.seed))
        (Path(test_dir_path) / "fuzzer_meta.json").write_text(json.dumps(
            {"operations": [o.op_id for o in selected], "paths": paths, "checks": CHECKS,
             "max_examples": MAX_EXAMPLES, "seed": self.seed, "seconds": round(time.time() - t0, 2)}, indent=1))
        return {"success": True, "test_file": str(test_file_path), "cost": 0.0}

    def get_usage_summary(self):
        return {"model_id": self.model_id, "requests": 0, "input_tokens": 0, "output_tokens": 0}
